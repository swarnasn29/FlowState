#!/usr/bin/env bash
# Capture a readable transcript of the whole system working, into docs/DEMO.md.
#
# Insurance. If the venue wifi dies, the endpoint is down, or a rate limit
# bites mid-pitch, this file is the proof - and it is readable by someone who
# never runs a command.
#
#   bash scripts/capture_demo.sh                   # no chain write
#   WITH_WEIGHTS=1 bash scripts/capture_demo.sh    # also commit weights
#
# WITH_WEIGHTS is off by default on purpose: committing weights consumes the
# chain's 100-block (~20 minute) rate limit, so capturing with it shortly
# before a live run would make the live SetWeights fail. Capture with weights
# when you are NOT about to demo.

set -uo pipefail

PROJECT=/mnt/c/Users/swarn/Documents/FlowStateProject
OUT="$PROJECT/docs/DEMO.md"
PORT_GOOD="${PORT_GOOD:-8091}"
PORT_WEAK="${PORT_WEAK:-8092}"
CHALLENGES="${CHALLENGES:-400}"

# shellcheck disable=SC1091
source "$HOME/venvs/flowstate/bin/activate"
cd "$PROJECT" || exit 1
mkdir -p "$PROJECT/docs"

# Strip per-request chatter; it adds hundreds of lines and no information.
denoise() {
  grep -vE "httpx +INFO|served #|Invalid HTTP request|flowstate\.miner INFO"
}

say() { printf '%s\n' "$*" >>"$OUT"; }
fence_start() { printf '```%s\n' "${1:-}" >>"$OUT"; }
fence_end() { printf '```\n' >>"$OUT"; }

: >"$OUT"

say "# FlowState — captured demo transcript"
say ""
say "Generated by \`scripts/capture_demo.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
say "Every block below is real output from the commands shown, against"
say "**netuid 600 on test.finney**. Nothing here is illustrative or edited"
say "beyond removing per-request log chatter."
say ""
say "---"
say ""

# ---------------------------------------------------------------- 1. the data
say "## 1. What the validator generates"
say ""
say "One user attempting a token swap, with exactly one friction point injected."
say "The arrow marks the injected step — the ground truth, which never leaves"
say "the validator."
say ""
fence_start
python - <<'PY' 2>&1 | denoise >>"$OUT"
from flowstate.telemetry import generate_task, render_session

for kind in ("stall", "silent_failure"):
    challenge, answer = generate_task(seed=1000, kind=kind)
    print(f"--- {kind} ---")
    print(render_session(challenge, answer))
    print()
PY
fence_end
say ""
say "Both examples are generated from the same seed, so the sessions are"
say "identical up to the injected fault — the differing rows are the friction,"
say "not noise."
say ""
say "The \`silent_failure\` case is the one UI-only analytics cannot see: no"
say "error, no rage-clicking, a dwell well inside what the step normally takes"
say "— and \`ui pending\` against \`chain confirmed\`. The transaction settled"
say "and the interface never found out."
say ""
say "Note \`quote_received\` carrying 6 rage-clicks in both: that is benign"
say "impatience, deliberately overlapping the injected \`rage_click\` range so"
say "that no single threshold can separate the two."
say ""

# ------------------------------------------------------------ 2. the detector
say "## 2. Does detection actually require skill?"
say ""
say '```'
say '$ python -m flowstate.detect_naive'
say '```'
say ""
fence_start
python -m flowstate.detect_naive 2>&1 | denoise >>"$OUT"
fence_end
say ""
say "\`python -m flowstate.detect\` additionally measures the zero-effort"
say "baselines on every run, so a label leaking back into the data would show"
say "up immediately rather than silently inflating every score."
say ""

# Start the miners before the pre-flight runs, so the captured pre-flight
# shows the state you want to be in rather than warning that nothing is
# listening yet.
PIDS=()
cleanup() {
  for pid in "${PIDS[@]:-}"; do
    kill "$pid" 2>/dev/null || true
    wait "$pid" 2>/dev/null || true
  done
}
trap cleanup EXIT

for spec in "miner:$PORT_GOOD:profile" "miner_naive:$PORT_WEAK:naive"; do
  IFS=: read -r hotkey port detector <<<"$spec"
  python -m neurons.miner --hotkey "$hotkey" --port "$port" \
    --detector "$detector" --no-serve-axon >/dev/null 2>&1 &
  PIDS+=("$!")
done

for port in "$PORT_GOOD" "$PORT_WEAK"; do
  for _ in $(seq 1 60); do
    (echo >"/dev/tcp/127.0.0.1/$port") 2>/dev/null && break
    sleep 0.5
  done
done

# -------------------------------------------------------------- 3. preflight
say "## 3. Pre-flight"
say ""
say "Asks whether a live run will work *right now* — which is a different"
say "question from whether the code is sound. It checks the chain's weight"
say "rate limit, has the chain validate a real \`SetWeights\` without"
say "submitting it, and confirms each published axon still points at this host"
say "and has something listening."
say ""
say '```'
say '$ python -m scripts.preflight --require-miners'
say '```'
say ""
fence_start
python -m scripts.preflight --require-miners 2>&1 | denoise >>"$OUT"
fence_end
say ""
say "With a miner stopped, the same two lines read"
say "\`FAIL ... IP correct but nothing listening\` and the verdict flips to"
say "NOT READY — it distinguishes that from a stale IP after a reboot, which"
say "looks identical from outside but needs re-publishing instead of a restart."
say ""

# --------------------------------------------------------- 4. the live run
say "## 4. Two miners, one validator, found via the metagraph"
say ""
say "Both miners are registered on netuid 600 and have published their"
say "endpoints on chain. The validator is told nothing about where they are."
say ""
say '```'
if [[ -n "${WITH_WEIGHTS:-}" ]]; then
  say "\$ SET_WEIGHTS=1 DISCOVER=1 bash scripts/demo_compare.sh"
else
  say "\$ DISCOVER=1 bash scripts/demo_compare.sh"
fi
say '```'
say ""
fence_start

VALIDATOR_ARGS=(--once --organic --challenges "$CHALLENGES")
[[ -n "${WITH_WEIGHTS:-}" ]] && VALIDATOR_ARGS+=(--set-weights)

# Keep the extrinsic id but drop the enormous raw event list after it.
python -m neurons.validator "${VALIDATOR_ARGS[@]}" 2>&1 \
  | denoise \
  | sed -E "s/(weights accepted: ExtrinsicResult\(success=[A-Za-z]+).*(extrinsic_id='[^']*').*/\1 \2)/" \
  >>"$OUT"

fence_end
say ""
say "The share column is the point: a 4-point accuracy difference becomes a"
say "material difference in emissions, because weight is"
say "\`max(0, accuracy - 0.70) ** 2\` rather than accuracy itself. A linear"
say "curve would pay the better miner about 4% more and nobody would improve."
say ""
say "The organic lines are the product: a session with no known answer, relayed"
say "to the miners, reports returned, deliberately **not** scored — there is no"
say "ground truth to score against, and inventing one would reward agreement"
say "with the validator rather than correctness."
say ""
say "---"
say ""
say "## Reproducing this"
say ""
say '```bash'
say 'source ~/venvs/flowstate/bin/activate'
say 'cd /mnt/c/Users/swarn/Documents/FlowStateProject'
say ''
say 'bash scripts/healthcheck.sh                 # 8 code checks'
say 'python -m scripts.preflight --require-miners  # will a run work now?'
say 'DISCOVER=1 bash scripts/demo_compare.sh     # the demo above'
say '```'

echo "wrote $OUT ($(wc -l <"$OUT") lines)"
